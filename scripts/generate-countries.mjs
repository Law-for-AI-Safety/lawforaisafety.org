// Regenerates src/opportunities/countries.ts from the `country-state-city` package's ISO
// 3166-1 country list. Run by hand (`node scripts/generate-countries.mjs`) when that package
// updates - not wired into any npm script, same as `scripts/seed-opportunities.mjs`.
import { writeFileSync } from "node:fs";
import { Country } from "country-state-city";

const countries = Country.getAllCountries()
  .map((c) => ({ code: c.isoCode, name: c.name }))
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = countries.map((c) => `  { code: ${JSON.stringify(c.code)}, name: ${JSON.stringify(c.name)} },`).join("\n");

const out = `/** Generated by scripts/generate-countries.mjs from the country-state-city package's ISO 3166-1 country list. */
export type Country = { code: string; name: string };

export const COUNTRIES: Country[] = [
${lines}
];
`;

writeFileSync(new URL("../src/opportunities/countries.ts", import.meta.url), out);
console.log(`Wrote ${countries.length} countries to src/opportunities/countries.ts`);
